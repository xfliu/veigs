# bench/bench_dumbbell.jl
#
# veigs on the dumbbell domain — clustered first-pair eigenvalues
# (the textbook spectral-geometry example). Optionally exports K, M
# to MatrixMarket .mtx files for cross-validation against MATLAB+INTLAB
# via veigs/bench_dumbbell.m.
#
# Usage:
#     /Volumes/DropboxDisk/AppDisk/Julia/bin/julia --project=. bench/bench_dumbbell.jl

using LinearAlgebra, SparseArrays, Printf
using Veigs
using IntervalArithmetic: sup, inf

include(joinpath(@__DIR__, "..", "test", "support", "laplacian2d_dumbbell.jl"))

const EXPORT     = true                              # set false to skip .mtx export
const EXPORT_DIR = joinpath(@__DIR__, "data")

function write_mtx(path::AbstractString, A::SparseMatrixCSC)
    n, m = size(A)
    rows, cols, vals = findnz(A)
    keep = rows .>= cols
    open(path, "w") do io
        println(io, "%%MatrixMarket matrix coordinate real symmetric")
        println(io, "% generated by Veigs.jl bench/bench_dumbbell.jl")
        println(io, "$n $m $(count(keep))")
        for k in eachindex(rows)
            keep[k] || continue
            @printf(io, "%d %d %.17g\n", rows[k], cols[k], vals[k])
        end
    end
end

EXPORT && mkpath(EXPORT_DIR)

println("veigs on dumbbell domain (two unit squares + bar w=0.2):")
println("(asking for 2 smallest — the clustered first pair)\n")

for (h, k_order) in ((0.1, 1), (0.05, 1), (0.025, 1),
                     (0.1, 2), (0.05, 2),
                     (0.1, 3))
    K, M, ndof, _ = laplacian2d_dumbbell(h, k_order)
    veigs(K, M, 2, :smallestabs)  # warm
    t = @elapsed for _ in 1:3
        veigs(K, M, 2, :smallestabs)
    end
    λ_int, _ = veigs(K, M, 2, :smallestabs)
    width1 = sup(λ_int[1]) - inf(λ_int[1])
    width2 = sup(λ_int[2]) - inf(λ_int[2])
    gap    = inf(λ_int[2]) - sup(λ_int[1])
    @printf("h=%.4f  P%d  ndof=%5d  wall=%6.3f s   λ_1=%.6f λ_2=%.6f  Δ=%.3e  width=%.2e\n",
            h, k_order, ndof, t/3, inf(λ_int[1]), inf(λ_int[2]), gap, max(width1, width2))
    if EXPORT
        tag = "h$(replace(string(h), '.' => 'p'))_p$(k_order)"
        write_mtx(joinpath(EXPORT_DIR, "K_dumbbell_$(tag).mtx"), K)
        write_mtx(joinpath(EXPORT_DIR, "M_dumbbell_$(tag).mtx"), M)
    end
end
