# bench/bench_laplacian2d_pk.jl
#
# Bench `veigs` on Pk Laplacian (k = 1, 2, 3) matrices on the unit square.
#
# Usage:
#     /Volumes/DropboxDisk/AppDisk/Julia/bin/julia --project=. bench/bench_laplacian2d_pk.jl
#
# Optionally exports the K, M matrices to MatrixMarket .mtx files in
# bench/data/ for cross-validation against MATLAB+INTLAB. Set
# `EXPORT = true` below to enable.

using LinearAlgebra, SparseArrays, Printf
using Veigs
using IntervalArithmetic: sup, inf

include(joinpath(@__DIR__, "..", "test", "support", "laplacian2d_pk.jl"))

const EXPORT     = false                 # set true to write .mtx files
                                          # (then run veigs/bench_laplacian2d_pk.m
                                          # for the MATLAB+INTLAB comparison)
const EXPORT_DIR = joinpath(@__DIR__, "data")

# Minimal MatrixMarket symmetric coordinate writer (lower triangle).
# Compatible with MATLAB's `mmread` (NIST File Exchange) and Julia's
# `MatrixMarket.jl`.
function write_mtx(path::AbstractString, A::SparseMatrixCSC)
    n, m = size(A)
    rows, cols, vals = findnz(A)
    keep = rows .>= cols
    open(path, "w") do io
        println(io, "%%MatrixMarket matrix coordinate real symmetric")
        println(io, "% generated by Veigs.jl bench/bench_laplacian2d_pk.jl")
        println(io, "$n $m $(count(keep))")
        for k in eachindex(rows)
            keep[k] || continue
            @printf(io, "%d %d %.17g\n", rows[k], cols[k], vals[k])
        end
    end
end

EXPORT && mkpath(EXPORT_DIR)

println("veigs(K, M, 1, :smallestabs) on Pk Laplacian (Ferrite assembler):")
println("(λ_min should approach 2π² ≈ 19.7392 as h → 0)")
println()

for (k, sweeps) in ((1, (16, 32, 64, 96)),
                    (2, (16, 32, 64)),
                    (3, (16, 32, 64)))
    println("--- P$k ---")
    for n_cells in sweeps
        K, M, ndof = laplacian2d_pk(n_cells, k)
        # Warm + bench
        veigs(K, M, 1, :smallestabs)
        t = @elapsed for _ in 1:3
            veigs(K, M, 1, :smallestabs)
        end
        λ, _ = veigs(K, M, 1, :smallestabs)
        width = sup(λ[1]) - inf(λ[1])
        @printf("  n_cells=%2d  ndof=%6d  median_wall=%6.3f s  λ_min=%.6f  width=%.2e  nnz(K)=%d\n",
                n_cells, ndof, t/3, inf(λ[1]), width, nnz(K))
        if EXPORT
            write_mtx(joinpath(EXPORT_DIR, "K_p$(k)_n$(n_cells).mtx"), K)
            write_mtx(joinpath(EXPORT_DIR, "M_p$(k)_n$(n_cells).mtx"), M)
        end
    end
    println()
end
